_CHALLENGES_BY_ID = {challenge["id"]: challenge for challenge in CHALLENGES}


def challenge_by_id(challenge_id):
    return _CHALLENGES_BY_ID.get(challenge_id)


def challenge_for_date(day):
    if not isinstance(day, date):
        raise TypeError("day must be a datetime.date")
    index = int.from_bytes(sha256(day.isoformat().encode("ascii")).digest()[:8], "big")
    return CHALLENGES[index % len(CHALLENGES)]
